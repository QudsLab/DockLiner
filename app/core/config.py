def _ensure_env_file() -> None:
    """If .env is missing, create a default one using the env refiner and reload settings."""
    env_path = Path(".env")
    if env_path.exists():
        return
    try:
        from app.env_maker import refine_env
        env_path.write_text(refine_env(""), encoding="utf-8")
        _log_stuck(".env was missing. Created default .env from template.")
    except Exception as e:
        _log_stuck(f".env was missing and could not be created: {e}")


def _reload_settings_from_env_file() -> None:
    """Load .env into os.environ so pydantic Settings sees the values."""
    env_path = Path(".env")
    if not env_path.exists():
        return
    try:
        with env_path.open("r", encoding="utf-8") as f:
            for line in f:
                stripped = line.strip()
                if not stripped or stripped.startswith("#") or "=" not in stripped:
                    continue
                key, _, value = stripped.partition("=")
                if key.startswith(_ENV_PREFIX):
                    os.environ[key] = value
    except Exception as e:
        _log_stuck(f"Could not reload .env into environment: {e}")


