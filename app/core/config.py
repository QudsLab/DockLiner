def _is_port_configured_explicitly() -> bool:
    """True if the user set DOCKLINER_PORT explicitly in the environment."""
    return f"{_ENV_PREFIX}PORT" in os.environ


def resolve_hosts() -> List[str]:
    """Return the configured host list. Defaults to ['0.0.0.0']."""
    raw = (settings.HOST or "0.0.0.0").strip()
    if not raw:
        return ["0.0.0.0"]
    hosts = [h.strip() for h in raw.split(",") if h.strip()]
    return hosts or ["0.0.0.0"]


def resolve_port() -> int:
    """
    Return the port the app must bind to.

    - If DOCKLINER_PORT is configured and free on every configured host -> use it.
    - If configured but occupied on any host ->
        * strict: raise RuntimeError
        * auto: try DOCKLINER_ALLOWED_PORTS whitelist in order (max 100 attempts),
          write the chosen port to .env, and return it.
    - If not configured:
        * strict: raise a well-organized error.
        * auto: start from default 50021, try whitelist, write chosen port to .env.
    """
    env_port = os.environ.get(f"{_ENV_PREFIX}PORT")
    hosts = resolve_hosts()

    if env_port:
        try:
            port = int(env_port)
        except ValueError:
            _log_stuck(f"DOCKLINER_PORT='{env_port}' is not a valid integer")
            raise RuntimeError(f"DOCKLINER_PORT='{env_port}' is not a valid integer.")
        if not _try_port(hosts, port):
            _log_stuck(f"DOCKLINER_PORT={port} is in use on at least one host among {hosts}")
            selection = (settings.PORT_SELECTION or "strict").lower().strip()
            if selection != "auto":
                raise RuntimeError(
                    f"DOCKLINER_PORT={port} is already in use on one of {','.join(hosts)}. "
                    "Set DOCKLINER_PORT to a free port or set DOCKLINER_PORT_SELECTION=auto."
                )
        else:
            return port

    selection = (settings.PORT_SELECTION or "strict").lower().strip()
    if selection != "auto":
        _log_stuck("DOCKLINER_PORT is not configured and DOCKLINER_PORT_SELECTION=strict")
        raise RuntimeError(
            "DOCKLINER_PORT is not configured. Set DOCKLINER_PORT=<free-port> "
            "or set DOCKLINER_PORT_SELECTION=auto to let DockLiner choose a free port."
        )

    # Auto mode: try whitelist in order, starting from DOCKLINER_PORT if present
    allowed = _allowed_ports()
    start_port = settings.PORT
    start_idx = 0
    if start_port in allowed:
        start_idx = allowed.index(start_port)
    candidates = allowed[start_idx:] + allowed[:start_idx]
    chosen = None
    attempts = 0
    for port in candidates:
        attempts += 1
        if attempts > 100:
            break
        if _try_port(hosts, port):
            chosen = port
            break
        _log_stuck(f"Port {port} is in use on one of {','.join(hosts)}")

    if chosen is None:
        _log_stuck("Could not find a free port in DOCKLINER_ALLOWED_PORTS after 100 attempts")
        raise RuntimeError(
            "Could not find a free port in DOCKLINER_ALLOWED_PORTS. "
            "Free a port from the whitelist or add more ports."
        )

    _write_env_value("PORT", str(chosen))
    os.environ[f"{_ENV_PREFIX}PORT"] = str(chosen)
    _log_stuck(f"Auto-selected free port {chosen} and wrote DOCKLINER_PORT={chosen} to .env")
    print(f"[DockLiner] Auto-selected free port: {chosen}")
    return chosen
