    SQLITE_DB_PATH: str = "./dockliner.db"
    SQLITE_DB_NAME: str = "dockliner"
    SQLITE_TEST_DB_PATH: str = "./dockliner_test.db"

    # ------------------------------------------------------------------
    # Application directories & runtime
    # ------------------------------------------------------------------
