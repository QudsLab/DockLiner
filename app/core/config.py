_ENV_PREFIX = "DOCKLINER_"


def _env(name: str, default: Optional[str] = None) -> Optional[str]:
    return os.environ.get(f"{_ENV_PREFIX}{name}", default)


def _log_stuck(message: str) -> None:
    """Append a startup issue to why_stuck.log."""
    from datetime import datetime
    log_path = Path("why_stuck.log")
    try:
        with log_path.open("a", encoding="utf-8") as f:
            f.write(f"[{datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S')}] {message}\n")
    except Exception:
        pass


def _log_login(line: str) -> None:
    """Append a login event to login_attempts.log."""
    from datetime import datetime
    log_path = Path("login_attempts.log")
    try:
        with log_path.open("a", encoding="utf-8") as f:
            f.write(f"[{datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S')}] {line}\n")
    except Exception:
        pass


def _ua_prefix(user_agent: str) -> str:
    """Return a 16-char blake3 prefix of the user agent for indexing."""
    from blake3 import blake3
    return blake3(user_agent.encode("utf-8")).hexdigest(length=8)


def log_login_attempt(user: str, ip: str, user_agent: str) -> None:
    ua = user_agent or ""
    _log_login(f"LOGIN_ATTEMPT user={user} ip={ip} ua_prefix={_ua_prefix(ua)} ua={ua}")


def log_login_success(user: str, ip: str, user_agent: str) -> None:
    ua = user_agent or ""
    _log_login(f"LOGIN_SUCCESS user={user} ip={ip} ua_prefix={_ua_prefix(ua)}")


def log_login_failure(user: str, ip: str, user_agent: str, reason: str = "bad_password") -> None:
    ua = user_agent or ""
    _log_login(f"LOGIN_FAILURE user={user} ip={ip} ua_prefix={_ua_prefix(ua)} reason={reason}")


def _write_env_value(key: str, value: str) -> None:
    """Update or append a single variable in .env without touching other lines."""
    env_path = Path(".env")
    prefix = f"{_ENV_PREFIX}{key}"
    line = f"{prefix}={value}"
    try:
        if env_path.exists():
            text = env_path.read_text(encoding="utf-8")
            lines = text.splitlines()
            found = False
            new_lines = []
            for ln in lines:
                stripped = ln.strip()
                if stripped.startswith(prefix) and ("=" in stripped or stripped == prefix):
                    new_lines.append(line)
                    found = True
                else:
                    new_lines.append(ln)
            if not found:
                new_lines.append(line)
            env_path.write_text("\n".join(new_lines) + "\n", encoding="utf-8")
        else:
            env_path.write_text(f"# Auto-generated by DockLiner on startup\n{line}\n", encoding="utf-8")
    except Exception as e:
        _log_stuck(f"Could not write {prefix} to .env: {e}")


def _ensure_secret_key() -> None:
    """If SECRET_KEY is the placeholder, generate a random 256-bit key and write it."""
    if settings.SECRET_KEY and settings.SECRET_KEY != "change-me":
        return
    new_key = secrets.token_hex(32)  # 256 bits = 64 hex chars
    _write_env_value("SECRET_KEY", new_key)
    os.environ[f"{_ENV_PREFIX}SECRET_KEY"] = new_key
    # update settings in-place
    try:
        settings.__dict__["SECRET_KEY"] = new_key
    except Exception:
        pass
    _log_stuck(f"Generated new DOCKLINER_SECRET_KEY and wrote it to .env")


def _is_prime(n: int) -> bool:
    if n < 2:
        return False
    if n % 2 == 0:
        return n == 2
    r = int(n ** 0.5)
    for i in range(3, r + 1, 2):
        if n % i == 0:
            return False
    return True


def _allowed_ports() -> List[int]:
    """Return the configured allowed ports whitelist, defaulting to prime 50xxx list."""
    raw = os.environ.get(f"{_ENV_PREFIX}ALLOWED_PORTS", "")
    if not raw:
        raw = "50021,50023,50033,50047,50051,50053,50069,50077,50087,50093,50101,50111,50119,50123"
    ports = []
    for part in raw.split(","):
        part = part.strip()
        if not part:
            continue
        try:
            ports.append(int(part))
        except ValueError:
            _log_stuck(f"Invalid port in DOCKLINER_ALLOWED_PORTS: {part}")
    return ports


def is_port_free(host: str, port: int) -> bool:
    """Return True if the given host/port is free to bind."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.5)
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


def _try_port(hosts: List[str], port: int) -> bool:
    """Return True if the port is free on every listed host."""
    for host in hosts:
        if not is_port_free(host, port):
            return False
    return True


