    DOWNLOADS_DIR: str = "./downloads"
    LOGS_DIR: str = "./logs"
    SECRET_KEY: str = "change-me"
    HOST: str = "0.0.0.0"
    PORT: int = 50021                    # "50 first prime" default port
    PORT_SELECTION: str = "strict"       # strict | auto
    ALLOWED_PORTS: str = "50021,50023,50033,50047,50051,50053,50069,50077,50087,50093,50101,50111,50119,50123"
    MAX_ACCESS_TOKENS: int = 10
