def _has_live_vars(prefix: str = "DB_LIVE_") -> bool:
    return any(
        os.environ.get(f"{_ENV_PREFIX}{prefix}{k}")
        for k in ("HOST", "USER", "PASSWORD", "NAME")
    )


def _has_test_vars(prefix: str = "DB_TEST_") -> bool:
    return any(
        os.environ.get(f"{_ENV_PREFIX}{prefix}{k}")
        for k in ("HOST", "USER", "PASSWORD", "NAME")
    )


def resolve_db_mode() -> str:
    """Return concrete DB_MODE: live | test, resolving auto if needed."""
    mode = (settings.DB_MODE or "auto").lower().strip()
    if mode not in ("auto", "test", "live"):
        raise ValueError(f"DOCKLINER_DB_MODE must be auto, test, or live. Got: {settings.DB_MODE}")
    if mode == "auto":
        if _has_live_vars():
            return "live"
        if _has_test_vars():
            return "test"
        return "test"
    return mode


def resolve_db_type(mode: Optional[str] = None) -> str:
    """Return concrete DB_TYPE for the current mode, defaulting to sqlite."""
    requested = (settings.DB_TYPE or "sqlite").lower().strip()
    valid = {"sqlite", "mysql", "postgres", "postgresql"}
    if requested not in valid:
        raise ValueError(f"DOCKLINER_DB_TYPE must be one of {valid}. Got: {settings.DB_TYPE}")
    concrete_mode = mode or resolve_db_mode()
    # live/test only matters for initialization / validation; type is independent.
    if concrete_mode in ("test", "live") and requested == "sqlite":
        return "sqlite"
    return requested


def build_database_url(mode: Optional[str] = None, db_type: Optional[str] = None) -> str:
    """Build SQLAlchemy URL from settings, honoring DB_MODE/DB_TYPE."""
    if settings.DATABASE_URL:
        return settings.DATABASE_URL

    concrete_mode = mode or resolve_db_mode()
    concrete_type = db_type or resolve_db_type(concrete_mode)

    if concrete_mode == "test" and concrete_type == "sqlite":
        path = settings.SQLITE_TEST_DB_PATH
        return f"sqlite:///{path}"

    if concrete_type == "sqlite":
        path = settings.SQLITE_DB_PATH or settings.DB_PATH
        return f"sqlite:///{path}"

    if concrete_type == "mysql":
        host = settings.DB_LIVE_HOST if concrete_mode == "live" else settings.DB_TEST_HOST
        port = settings.DB_LIVE_PORT if concrete_mode == "live" else settings.DB_TEST_PORT
        user = settings.DB_LIVE_USER if concrete_mode == "live" else settings.DB_TEST_USER
        password = settings.DB_LIVE_PASSWORD if concrete_mode == "live" else settings.DB_TEST_PASSWORD
        db_name = settings.DB_LIVE_NAME if concrete_mode == "live" else settings.DB_TEST_NAME
        port = port or 3306
        driver = settings.DB_DRIVER if settings.DB_DRIVER and "mysql" in settings.DB_DRIVER else "pymysql"
        return f"mysql+{driver}://{user}:{password}@{host}:{port}/{db_name}"

    if concrete_type in ("postgres", "postgresql"):
        host = settings.DB_LIVE_HOST if concrete_mode == "live" else settings.DB_TEST_HOST
        port = settings.DB_LIVE_PORT if concrete_mode == "live" else settings.DB_TEST_PORT
        user = settings.DB_LIVE_USER if concrete_mode == "live" else settings.DB_TEST_USER
        password = settings.DB_LIVE_PASSWORD if concrete_mode == "live" else settings.DB_TEST_PASSWORD
        db_name = settings.DB_LIVE_NAME if concrete_mode == "live" else settings.DB_TEST_NAME
        port = port or 5432
        driver = settings.DB_DRIVER if settings.DB_DRIVER and "psycopg" in settings.DB_DRIVER else "psycopg2"
        return f"postgresql+{driver}://{user}:{password}@{host}:{port}/{db_name}"

    raise ValueError(f"Unsupported DOCKLINER_DB_TYPE: {settings.DB_TYPE}")


def require_live_vars() -> None:
    """Validate that live database variables are present when DB_MODE=live."""
    # SQLite live mode only needs a path; user/password are not used.
    if (settings.DB_TYPE or "sqlite").lower().strip() == "sqlite":
        return
    missing = []
    if not settings.DB_LIVE_HOST:
        missing.append("DOCKLINER_DB_LIVE_HOST")
    if not settings.DB_LIVE_USER:
        missing.append("DOCKLINER_DB_LIVE_USER")
    if not settings.DB_LIVE_PASSWORD:
        missing.append("DOCKLINER_DB_LIVE_PASSWORD")
    if not settings.DB_LIVE_NAME:
        missing.append("DOCKLINER_DB_LIVE_NAME")
    if missing:
        raise ValueError(
            f"DB_MODE=live with a non-SQLite database requires the following environment variables: {', '.join(missing)}"
        )


def validate_db_config() -> None:
    """Run mode-specific validation. Log issues to why_stuck.log."""
    try:
        mode = resolve_db_mode()
    except Exception as e:
        _log_stuck(f"DB_MODE resolution failed: {e}")
        raise
    try:
        db_type = resolve_db_type(mode)
    except Exception as e:
        _log_stuck(f"DB_TYPE resolution failed: {e}")
        raise
    try:
        if mode == "live":
            require_live_vars()
        if mode == "test" and db_type != "sqlite" and not _has_test_vars():
            raise ValueError(
                "DB_MODE=test with a non-SQLite database requires DOCKLINER_DB_TEST_HOST, "
                "DOCKLINER_DB_TEST_USER, DOCKLINER_DB_TEST_PASSWORD, and DOCKLINER_DB_TEST_NAME"
            )
    except Exception as e:
        _log_stuck(f"DB config validation failed: {e}")
        raise


